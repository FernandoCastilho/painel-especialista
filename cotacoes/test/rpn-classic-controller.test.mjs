test('PSE pauses one second, notifies resumed state, and a key stops without executing it',()=>{
 let next=0
 const schedule=new Map(), observed=[]
 const c=createClassicRpnController({
   schedule:(callback,ms)=>{assert.equal(ms,1000);schedule.set(++next,callback);return next},
   cancelScheduled:(id)=>schedule.delete(id),
 })
 const unsubscribe=c.subscribe(state=>observed.push([state.x,state.indicators.paused]))
 run(c,'f','runStop','2','enter','g','runStop','3','add','f','runStop','g','roll','0','0','runStop')
 assert.equal(c.snapshot().x,2);assert.equal(c.snapshot().indicators.paused,true)
 const finish=()=>{const [id,fn]=schedule.entries().next().value;schedule.delete(id);fn()}
 finish();assert.deepEqual(observed,[[5,false]])
 run(c,'g','roll','0','0','runStop');assert.equal(c.snapshot().indicators.paused,true)
 run(c,'9');assert.equal(c.snapshot().x,2);assert.equal(schedule.size,0)
 run(c,'runStop');assert.equal(c.snapshot().x,5)
 run(c,'g','roll','0','0','runStop')
 unsubscribe();c.dispose();assert.equal(schedule.size,0)
})
