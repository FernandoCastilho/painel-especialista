import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
import { buildKnowledgeGraph } from '../src/knowledgeGraph.js'
import { buildSectorKnowledgeGraph } from '../src/sectorKnowledgeGraph.js'
import { TIC_STUDY } from '../src/ticStudy.js'

const output = new URL('../src/generated.sectorKnowledge.js', import.meta.url)
export async function sectorKnowledgeSource() {
  const studies = JSON.parse(await readFile(new URL('../src/sectorStudies/studies.json', import.meta.url), 'utf8'))
  const graph = buildKnowledgeGraph({ now: 1 })
  const connections = []
  for (const study of [...studies, { ...TIC_STUDY, group: 'tic', topicIndex: 0 }]) {
    const scoped = buildSectorKnowledgeGraph(graph, { group: study.group, topicIndex: study.topicIndex, study })
    for (const link of scoped.links.filter(link => link.evidence)) {
      const { section, term, excerpt } = link.evidence
      // Store the exact passage, not a machine-generated economic assertion.
      connections.push([link.source, link.target, term, section, excerpt])
    }
  }
  connections.sort((a, b) => a[0].localeCompare(b[0]) || a[1].localeCompare(b[1]))
  return `// Generated by scripts/build-sector-knowledge.mjs. Do not edit manually.\nexport const SECTOR_STUDY_CONNECTIONS = ${JSON.stringify(connections)}\n`
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = await sectorKnowledgeSource()
  if (process.argv.includes('--check')) {
    if (source !== await readFile(output, 'utf8')) throw new Error('Relações dos estudos desatualizadas. Execute node scripts/build-sector-knowledge.mjs.')
  } else await writeFile(output, source)
}
