const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const base = process.env.SMOKE_BASE_URL || 'http://127.0.0.1:8768'
const out = process.env.BALANCE_QA_OUTPUT || 'workspace-qa/balancos'
;(async()=>{
 fs.mkdirSync(out,{recursive:true})
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||undefined,headless:true,args:['--no-sandbox']})
 const errors=[],leaks=[];let page
 try {
  page=await browser.newPage({viewport:{width:1440,height:1000}})
  page.on('pageerror',e=>errors.push(e.message))
  page.on('dialog',dialog=>dialog.accept())
  const marker='BALANCE-PRIVATE-SYNTHETIC-9917'
  const {sampleAnalysis,annualCsv}=await import('../src/balanceAnalysis.js')
  page.on('request',request=>{if((request.url()+(request.postData()||'')).includes(marker))leaks.push(request.url())})
  await page.route('**/*',route=>route.request().url().startsWith(base+'/')?route.continue():route.abort())
  await page.goto(`${base}/#balancos`)
  await page.getByRole('heading',{name:'Dos números às perguntas certas'}).waitFor()
  const app=page.locator('.balance-analysis')
  await app.getByRole('button',{name:'Gerar análise',exact:true}).first().click()
  await app.getByRole('heading',{name:'Empresa não identificada'}).waitFor()
  assert.match(await app.innerText(),/Não calculável/)
  await app.getByRole('button',{name:'Exemplo sintético',exact:true}).click()
  await app.getByLabel('Empresa ou identificação interna',{exact:true}).fill(marker)
  await app.getByLabel('Mostrar inferências financeiras limitadas, identificadas como não conclusivas',{exact:true}).check()
  await app.getByRole('button',{name:'Gerar análise',exact:true}).first().click()
  assert.match(await app.locator('.ba-report').innerText(),/Inferência — não conclusiva/)
  assert.match(await app.locator('.ba-report').innerText(),/não confirma mudança na capacidade de pagamento/)
  for(const theme of ['light','dark']){
   await page.emulateMedia({colorScheme:theme})
   for(const width of [390,820,1440]){
    await page.setViewportSize({width,height:1000})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`${theme}/${width} overflow`)
    await page.screenshot({path:path.join(out,`${theme}-${width}.png`),fullPage:true})
   }
  }
  await app.getByRole('button',{name:'Editar dados',exact:true}).click()
  await app.getByLabel('Receita líquida '+(new Date().getFullYear()-1),{exact:true}).fill('')
  assert.equal(await app.getByRole('button',{name:'Análise',exact:true}).isDisabled(),true,'stale report must be invalidated')
  await app.getByRole('button',{name:'Gerar análise',exact:true}).first().click()
  assert.match(await app.locator('.ba-report').innerText(),/Não informado/)
  await app.locator('input[type=file]').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{bad')})
  assert.match(await app.getByRole('alert').innerText(),/Importação não aplicada/)
  assert.equal(await app.getByRole('heading',{name:marker,exact:true}).count(),1,'invalid import preserves data')
  const imported=sampleAnalysis();imported.company=marker;imported.years[0].values.revenue={value:100,status:'Divergente',source:'Documento sintético A/B'}
  await app.locator('input[type=file]').setInputFiles({name:'data.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(imported))})
  await app.getByLabel('Empresa ou identificação interna',{exact:true}).waitFor()
  await app.getByLabel('Receita líquida '+imported.years[0].year,{exact:true}).fill('100')
  const exportEvent=page.waitForEvent('download');await app.getByRole('button',{name:'Exportar dados',exact:true}).click()
  const exported=JSON.parse(fs.readFileSync(await(await exportEvent).path(),'utf8'))
  assert.equal(exported.years[0].values.revenue.source,'Documento sintético A/B')
  assert.equal(exported.years[0].values.revenue.status,'Informado')
  await app.locator('input[type=file]').setInputFiles({name:'annual.csv',mimeType:'text/csv',buffer:Buffer.from(annualCsv(sampleAnalysis()))})
  assert.equal(await app.getByLabel('Receita líquida '+imported.years[0].year,{exact:true}).inputValue(),'100')
  await app.getByRole('button',{name:'Gerar análise',exact:true}).first().click()
  await app.locator('input[type=file]').setInputFiles({name:'divergence.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(imported))})
  await app.getByRole('button',{name:'Gerar análise',exact:true}).first().click()
  assert.match(await app.locator('.ba-report').innerText(),/Divergente/)
  assert.equal(await page.evaluate(marker=>Object.values(localStorage).some(v=>v.includes(marker))||Object.values(sessionStorage).some(v=>v.includes(marker)),marker),false)
  assert.deepEqual(leaks,[])
  await page.reload()
  assert.equal(await app.getByLabel('Empresa ou identificação interna',{exact:true}).inputValue(),'','reload discards inputs')
  assert.deepEqual(errors,[])
  fs.writeFileSync(path.join(out,'result.json'),JSON.stringify({passed:true,checks:['empty partial report','synthetic analysis','optional inference','valid JSON and CSV import','source preserved on correction','divergent cell blocked','invalid import atomic','stale outputs invalidated','390/820/1440 light/dark','no input storage or request leak','reload discards data'],errors,leaks},null,2))
  console.log('Balance analysis browser checks passed')
 }catch(error){if(page)await page.screenshot({path:path.join(out,'failure.png'),fullPage:true}).catch(()=>{});throw error}finally{await browser.close()}
})().catch(error=>{console.error(error);process.exit(1)})
