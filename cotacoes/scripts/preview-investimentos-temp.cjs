// Temporário: capturas da tela de Investimentos com a base real da CVM publicada. Sai antes de juntar.
const { chromium } = require('playwright')
const fs = require('node:fs')
const out = process.env.OUT
const site = 'https://fernandocastilho.github.io/painel-especialista'
;(async () => {
  fs.mkdirSync(out, { recursive: true })
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  for (const width of [1280, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, serviceWorkers: 'block', deviceScaleFactor: 1 })
    page.setDefaultTimeout(60000)
    await page.route(url => url.pathname.includes('/cvm/'), async route => {
      const nome = new URL(route.request().url()).pathname.split('/cvm/')[1]
      const resp = await route.fetch({ url: site + '/cvm/' + nome })
      await route.fulfill({ response: resp })
    })
    await page.goto('http://127.0.0.1:8768/#calculadora/investimentos')
    const region = page.getByRole('region', { name: 'Investimentos', exact: true })
    const busca = region.getByRole('searchbox', { name: 'Buscar ativo' })
    await busca.waitFor()
    await busca.fill('santander renda fixa referenciado')
    await region.getByRole('list', { name: 'Ativos encontrados' }).getByRole('button').first().waitFor()
    await page.waitForTimeout(800)
    await region.getByRole('list', { name: 'Ativos encontrados' }).screenshot({ path: `${out}/1-busca-${width}.png` })
    const nomes = await region.getByRole('list', { name: 'Ativos encontrados' }).getByRole('button').allInnerTexts()
    console.log('BUSCA', width, JSON.stringify(nomes.slice(0, 8)))
    await region.getByRole('list', { name: 'Ativos encontrados' }).getByRole('button').first().click()
    await busca.fill('itau multimercado credito privado')
    await region.getByRole('list', { name: 'Ativos encontrados' }).getByRole('button').first().click()
    const chart = region.getByRole('region', { name: 'Rentabilidade acumulada', exact: true })
    await chart.waitFor()
    await chart.getByRole('textbox', { name: 'Valor aplicado', exact: true }).fill('10.000')
    await page.waitForTimeout(1500)
    await region.getByRole('region', { name: 'Ativos em comparação' }).screenshot({ path: `${out}/2-ativos-${width}.png` })
    await chart.screenshot({ path: `${out}/3-grafico-${width}.png` })
    console.log('ATIVOS', width, (await region.getByRole('region', { name: 'Ativos em comparação' }).innerText()).replace(/\s+/g, ' '))
    console.log('LEGENDA', width, (await chart.getByRole('list', { name: 'Rentabilidade dos ativos na data selecionada' }).innerText()).replace(/\s+/g, ' '))
    console.log('NOTAS', width, (await region.locator('p.inv-nota').allInnerTexts()).join(' | '))
    await region.getByRole('button', { name: 'Consultar fundos', exact: true }).click()
    await page.waitForTimeout(1000)
    console.log('BASE', width, (await region.locator('p.inv-nota').allInnerTexts()).join(' | '))
    await page.close()
  }
  await browser.close()
})().catch(e => { console.error(e); process.exit(1) })
