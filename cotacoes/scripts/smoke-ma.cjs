const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const http = require('node:http')
const root = path.resolve(__dirname,'../dist')
const output = process.env.MA_QA_OUTPUT || path.resolve(__dirname,'../../docs/ma-qa')
// Contagens tiradas do próprio catálogo: o acervo cresce a cada atualização.
const { transactions } = JSON.parse(fs.readFileSync(path.resolve(__dirname,'../src/ma/transactions.json'),'utf8'))
const year2026 = transactions.filter(row => (row.announcementDate || row.publicationDate).startsWith('2026')).length
const page1 = count => String(Math.min(10,count))
const types = {'.html':'text/html','.js':'text/javascript','.css':'text/css','.json':'application/json','.svg':'image/svg+xml','.woff2':'font/woff2','.webp':'image/webp'}
const server = http.createServer((req,res) => {
  const requestPath = decodeURIComponent(new URL(req.url,'http://127.0.0.1').pathname).replace(/^\/painel-especialista/,'')
  const file = path.resolve(root,'.' + (requestPath === '/' ? '/index.html' : requestPath))
  if (!file.startsWith(root + path.sep)) { res.writeHead(403).end(); return }
  fs.readFile(file,(error,data) => { if(error) res.writeHead(404).end(); else { res.setHeader('Content-Type',types[path.extname(file)] || 'application/octet-stream'); res.end(data) } })
})
;(async () => {
  fs.mkdirSync(output,{recursive:true})
  await new Promise(resolve => server.listen(0,'127.0.0.1',resolve))
  const base = `http://127.0.0.1:${server.address().port}/`
  const browser = await chromium.launch(require('./smoke-launch.cjs')())
  const report = []
  try {
    for(const width of [320,390,820,1024,1440,1920]) for(const theme of ['light','dark']) {
      const context = await browser.newContext({viewport:{width,height:1050},colorScheme:theme,serviceWorkers:'block'})
      const page = await context.newPage()
      const errors = []
      page.on('pageerror',error => errors.push(error.message))
      await page.route('https://**/*',route => route.abort())
      await page.goto(base + '#ma')
      await page.locator('.ma-module').waitFor()
      await page.evaluate(() => document.fonts.ready)
      // abre no ano mais recente (2026)
      assert.equal(await page.locator('.ma-metric strong').first().innerText(),String(year2026))
      assert.ok(await page.locator('.ma-bubble').count() > 3)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1),true,'sem rolagem horizontal na página')
      const nav = page.getByRole('navigation',{name:width >= 1000 ? 'Navegação principal' : 'Seções',exact:true})
      for (const button of await nav.locator(':scope > button, :scope > .more-tab > button').all()) {
        const bounds = await button.boundingBox()
        assert.ok(bounds.width >= 44 && bounds.height >= 44 && bounds.x >= 0 && bounds.x + bounds.width <= width + 1,`menu acessível em ${width}: ${await button.innerText()}`)
      }
      if(width >= 1000) {
        const ma = nav.getByRole('button',{name:'M&A',exact:true})
        assert.ok(await ma.isVisible())
        const box = await ma.boundingBox()
        assert.ok(box.x >= 0 && box.x + box.width <= width)
      } else {
        await nav.getByRole('button',{name:'Mais',exact:true}).click()
        await nav.getByRole('menuitem',{name:'M&A',exact:true}).click()
      }
      await page.locator('.ma-module').screenshot({path:path.join(output,`visao-geral-${width}-${theme}.png`)})
      if (width === 1440 && theme === 'light') await page.screenshot({path:path.join(output,'ma-desktop.png'),fullPage:true})
      await page.goto(base + '#ma/visao-geral?year=2025')
      await page.locator('.ma-map').waitFor()
      assert.equal(await page.locator('.ma-metric strong').allTextContents().then(x=>x.join(',')),'5,3,3')
      assert.equal(await page.locator('.ma-bubble').count(),3)
      await page.getByRole('button',{name:'MA: 1 transação. Ver lista.',exact:true}).press('Enter')
      assert.equal(await page.locator('.ma-list tbody tr').count(),1)
      await page.locator('.ma-list tbody button').click()
      assert.match(await page.locator('.ma-detail').innerText(),/Dasa|São Domingos/)
      assert.equal(await page.locator('.ma-detail h3').evaluate(el => el === document.activeElement),true)
      assert.equal(await page.locator('.ma-detail h3').evaluate(el=>{const r=el.getBoundingClientRect();return r.top>=0&&r.bottom<innerHeight-80}),true,'detalhe selecionado entra na tela')
      await page.locator('.ma-detail').screenshot({path:path.join(output,`detalhe-${width}-${theme}.png`)})
      await page.getByRole('button',{name:'Ver em Setores → Saúde',exact:true}).click()
      await page.locator('.ma-sector-link').waitFor()
      await page.locator('.ma-sector-link').getByRole('link',{name:'Consultar transações do setor →',exact:true}).click()
      await page.locator('.ma-list tbody tr').first().waitFor()
      assert.equal(String(await page.locator('.ma-list tbody tr').count()),page1(transactions.filter(row => row.sectorId === 'saude').length))
      await page.getByRole('button',{name:'Limpar filtros',exact:true}).click()
      assert.equal(String(await page.locator('.ma-list tbody tr').count()),page1(transactions.length))
      await page.locator('.ma-list tbody button').first().click()
      assert.equal(await page.locator('.ma-detail h3').evaluate(el=>{const r=el.getBoundingClientRect();return r.top>=0&&r.bottom<innerHeight-80}),true,'detalhe entra na tela após lista completa')
      await page.getByRole('button',{name:'Limpar filtros',exact:true}).click()
      await page.getByRole('searchbox',{name:'Buscar empresa ou transação',exact:true}).focus()
      await page.getByRole('searchbox',{name:'Buscar empresa ou transação',exact:true}).scrollIntoViewIfNeeded()
      const searchScroll = await page.evaluate(()=>scrollY)
      await page.getByRole('searchbox',{name:'Buscar empresa ou transação',exact:true}).fill('neogrid')
      const afterSearchScroll = await page.evaluate(()=>scrollY)
      assert.ok(Math.abs(afterSearchScroll - searchScroll) < 3,`busca preserva rolagem: ${searchScroll} → ${afterSearchScroll}`)
      assert.equal(await page.locator('.ma-list tbody tr').count(),1)
      await page.getByRole('button',{name:'Limpar filtros',exact:true}).click()
      await page.getByLabel('Ano',{exact:true}).fill('2026')
      await page.getByLabel('Ano',{exact:true}).press('Tab')
      await page.locator('.ma-list tbody tr').first().waitFor()
      assert.match(await page.locator('.ma-selection [role="status"]').innerText(),new RegExp(`^${year2026} transações`))
      assert.equal(String(await page.locator('.ma-list tbody tr').count()),page1(year2026))
      await page.goto(base + '#ma/visao-geral?year=2025&sector=tic')
      await page.locator('.ma-module').waitFor()
      assert.equal(await page.locator('.ma-metric strong').first().innerText(),'3')
      await page.getByRole('button',{name:'Ver transações do recorte →',exact:true}).click()
      assert.equal(await page.locator('.ma-list tbody tr').count(),3)
      await page.goBack()
      await page.locator('.ma-map').waitFor()
      assert.ok(page.url().includes('sector=tic'))
      assert.deepEqual(errors,[])
      report.push({width,theme,result:'ok'})
      await context.close()
    }
    fs.writeFileSync(path.join(output,'report.json'),JSON.stringify(report,null,2)+'\n')
    console.log(JSON.stringify(report))
  } finally { await browser.close(); server.close() }
})().catch(error => { console.error(error); server.close(); process.exitCode = 1 })
