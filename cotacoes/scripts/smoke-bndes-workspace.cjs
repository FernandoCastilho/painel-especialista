const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const base = process.env.SMOKE_BASE_URL || 'http://127.0.0.1:8768'
const out = process.env.BNDES_WORKSPACE_QA_OUTPUT || 'workspace-qa/bndes-workspace'

;(async () => {
  fs.mkdirSync(out, { recursive: true })
  const browser = await chromium.launch(require('./smoke-launch.cjs')())
  const report = [], failures = []
  try {
    for (const width of [320, 390, 768, 1440]) for (const theme of ['light', 'dark']) {
      const page = await browser.newPage({ viewport: { width, height: 1000 }, colorScheme: theme, reducedMotion: 'reduce', serviceWorkers: 'block' })
      const errors = []; page.on('pageerror', error => errors.push(error.message))
      try {
        await page.route('**/bndes.json*', route => route.fulfill({ json: { schemaVersion: 1, generatedAt: Date.now(), series: { TFB_60_90: { points: [['2026-11-06', 13]] }, TFB_60_30: { points: [['2026-11-06', 13.2]] } }, tlp: { points: [['2026-11-01', 7]] }, errors: [], stale: {} } }))
        await page.route('**/moedas.json*', route => route.fulfill({ json: { schemaVersion: 1, generatedAt: Date.now(), series: { C03: { points: [['2026-11-06', 12]] }, C01: { points: [['2026-11-06', 12.5]] } }, errors: [], stale: {} } }))
        await page.goto(base + '/#calculadora')
        await page.getByRole('button', { name: 'BNDES: abrir calculadora', exact: true }).waitFor()
        assert.equal(await page.getByRole('button', { name: /^BNDES.*abrir calculadora$/ }).count(), 1, 'entrada única BNDES')
        await page.getByRole('button', { name: 'BNDES: abrir calculadora', exact: true }).click()
        await page.locator('#fm-compare').waitFor()
        if (width <= 390) {
          const amount = page.locator('#fm-valor')
          for (const value of ['500.000,00', '1.234.567,89']) {
            await amount.fill(value)
            await amount.blur()
            const geometry = await amount.evaluate(element => {
              const style = getComputedStyle(element)
              const context = document.createElement('canvas').getContext('2d')
              context.font = style.font
              return { value: element.value, focused: document.activeElement === element, textWidth: context.measureText(element.value).width, available: element.clientWidth - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight) }
            })
            assert.equal(geometry.value, value)
            assert.equal(geometry.focused, false)
            assert.ok(geometry.textWidth <= geometry.available, `valor completo e centavos visíveis: ${JSON.stringify(geometry)}`)
            await page.screenshot({ path: path.join(out, `${width}-${theme}-amount-${value.includes('89') ? 'cents' : 'default'}.png`), fullPage: true })
          }
          await amount.fill('500.000,00')
          await amount.blur()
        }
        await page.screenshot({ path: path.join(out, `${width}-${theme}-initial.png`), fullPage: true })
        assert.equal(await page.locator('#fm-custo').evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(255, 255, 255)', 'campos claros também no tema escuro')
        await page.locator('#fm-finame-eligible').check()
        // Os números principais abrem o resultado, sem precisar abrir a composição; a faixa "Cotação comparativa" só existe ao comparar.
        const highlights = page.locator('.fm-destaques tbody tr')
        await highlights.first().waitFor()
        assert.deepEqual((await highlights.locator('th').allInnerTexts()).map(text => text.replace(/\s*\?\s*$/, '').trim()), ['Taxa de referência', 'Taxa final', 'Primeira parcela após carência', 'Juros totais', 'IOF', 'Total projetado'])
        for (const item of await highlights.all()) assert.equal(await item.isVisible(), true)
        assert.equal(await page.locator('.fm-details').evaluate(element => element.open), false)
        assert.equal(await page.locator('.fm-hero').count(), 0)
        for (const box of await page.locator('.fm-destaques .fi-help > button').evaluateAll(buttons => buttons.map(button => { const rect = button.getBoundingClientRect(); return { width: rect.width, height: rect.height } }))) assert.ok(box.width >= 44 && box.height >= 44, 'ajuda da tabela com alvo de 44px')
        const topValues = await page.locator('.fm-summary-row td').allInnerTexts()
        await page.locator('.fm-details > summary').click()
        const detailValues = await page.locator('.fm-details .fm-kpi').allInnerTexts()
        for (const value of topValues) assert.ok(detailValues.some(detail => detail.includes(value.split('\n')[0])), 'mesmo valor na composição: ' + value)
        await page.locator('.fm-details > summary').click()
        assert.equal(await page.locator('.fm-summary').count(), 0, 'resumo duplicado removido')
        assert.equal(await page.locator('.fm-comparison').count(), 0)
        await page.locator('#fm-compare').check()
        await page.locator('.fm-comparison table').waitFor()
        assert.match(await page.locator('.fm-hero h3').innerText(), /Cotação comparativa/)
        assert.equal(await highlights.count(), 0, 'comparação substitui tabela simples sem duplicar resultados')
        assert.match(await page.locator('.fm-comparison').innerText(), /TFB_60_90/)
        assert.match(await page.locator('.fm-comparison').innerText(), /C03/)
        assert.match(await page.locator('.fm-comparison').innerText(), /06\/11\/2026/)
        assert.match(await page.locator('.fm-difference').innerText(), /maior/)
        await page.getByRole('button', { name: 'Apresentar simulação', exact: true }).click()
        const settings = page.getByRole('dialog', { name: 'Configurar apresentação BNDES', exact: true })
        await settings.waitFor()
        await settings.locator('#bnp-title').fill('Simulação ilustrativa BNDES')
        await settings.getByText('Ajustes de apresentação', { exact: true }).click()
        await page.screenshot({ path: path.join(out, `${width}-${theme}-settings.png`), fullPage: true })
        await settings.getByRole('button', { name: 'Iniciar apresentação', exact: true }).click()
        const presentation = page.getByRole('dialog', { name: 'Apresentação BNDES', exact: true })
        await presentation.waitFor()
        await page.screenshot({ path: path.join(out, `${width}-${theme}-presentation.png`), fullPage: true })
        await page.keyboard.press('ArrowRight')
        await presentation.getByRole('heading', { name: 'Condições e referências', exact: true }).waitFor()
        await page.keyboard.press('ArrowRight')
        await presentation.getByRole('heading', { name: 'TFC e TFB lado a lado', exact: true }).waitFor()
        assert.match(await presentation.innerText(), /não é CET/)
        const headingStyle = await presentation.locator('.bnp-slide h2').evaluate(element => ({ size: parseFloat(getComputedStyle(element).fontSize), color: getComputedStyle(element).color }))
        assert.ok(headingStyle.size >= 24, 'título de slide preserva tamanho de apresentação')
        assert.equal(headingStyle.color, 'rgb(0, 13, 60)')
        assert.equal(await presentation.locator('.bnp-table-wrap').evaluate(element => element.scrollHeight <= element.clientHeight + 1), true, 'tabela não corta linhas por redução vertical')
        const tableRegion = presentation.getByRole('region', { name: 'Resultados da simulação BNDES', exact: true })
        await tableRegion.press('ArrowRight')
        await presentation.getByRole('heading', { name: 'TFC e TFB lado a lado', exact: true }).waitFor()
        await tableRegion.press('ArrowLeft')
        await presentation.getByRole('heading', { name: 'TFC e TFB lado a lado', exact: true }).waitFor()
        await tableRegion.press('End')
        await presentation.getByRole('heading', { name: 'Premissas e limites', exact: true }).waitFor()
        assert.equal(await presentation.locator('.bnp-player').evaluate(element => element === document.activeElement), true, 'troca de slide recupera foco quando a tabela sai da tela')
        await page.keyboard.press('Home')
        await presentation.getByRole('heading', { name: 'Condições da operação', exact: true }).waitFor()
        await page.keyboard.press('ArrowRight')
        await page.keyboard.press('ArrowRight')
        await presentation.getByRole('heading', { name: 'TFC e TFB lado a lado', exact: true }).waitFor()
        await page.screenshot({ path: path.join(out, `${width}-${theme}-presentation-comparison.png`), fullPage: true })
        const laser = presentation.locator('.bnp-controls .laser-btn')
        await laser.waitFor()
        await laser.click()
        await presentation.locator('.bnp-player .laser-canvas').waitFor()
        await page.keyboard.press('Escape')
        await presentation.locator('.bnp-player .laser-canvas').waitFor({ state: 'hidden' })
        assert.equal(await presentation.isVisible(), true, 'primeiro Escape desliga o apontador')
        await presentation.getByRole('button', { name: 'Tela cheia', exact: true }).click()
        await page.waitForFunction(() => !!document.fullscreenElement || !!document.querySelector('.bnp-fullscreen-status'))
        const fullscreen = await page.evaluate(() => document.fullscreenElement?.classList.contains('bnp-player') === true)
        if (fullscreen) await presentation.getByRole('button', { name: 'Tela cheia', exact: true }).click()
        else assert.match(await presentation.locator('.bnp-fullscreen-status').innerText(), /continua nesta janela/)
        for (let tab = 0; tab < 8; tab++) {
          await page.keyboard.press('Tab')
          assert.equal(await presentation.evaluate(element => element.contains(document.activeElement)), true, 'foco permanece na apresentação')
        }

        await presentation.locator('.bnp-player').press('ArrowRight')
        await presentation.getByRole('heading', { name: 'Fluxo ilustrativo', exact: true }).waitFor()
        await page.screenshot({ path: path.join(out, `${width}-${theme}-flow.png`), fullPage: true })
        await page.keyboard.press('End')
        await presentation.getByRole('heading', { name: 'Premissas e limites', exact: true }).waitFor()
        await page.screenshot({ path: path.join(out, `${width}-${theme}-premises.png`), fullPage: true })
        await presentation.getByRole('button', { name: 'Configurar', exact: true }).click()
        await settings.waitFor()
        assert.equal(await settings.locator('#bnp-title').evaluate(element => element === document.activeElement), true)
        await page.keyboard.press('Escape')
        await presentation.waitFor({ state: 'hidden' })
        assert.equal(await page.getByRole('button', { name: 'Apresentar simulação', exact: true }).evaluate(element => element === document.activeElement), true)
        await page.locator('#fm-valor').fill('600.000,00')
        const before = await page.locator('.fm-comparison table').innerText()
        await page.getByRole('button', { name: 'Taxas e históricos', exact: true }).click()
        await page.locator('.bw-quotes .bn-table.bn-main').waitFor()
        for (const family of ['TFC', 'TFB', 'TLP', 'Moedas']) await page.locator('.bw-quotes .bn-fam').getByRole('button', { name: family, exact: true }).click()
        await page.getByRole('button', { name: 'Simular financiamento', exact: true }).click()
        assert.equal(await page.locator('#fm-valor').inputValue(), '600.000,00')
        assert.equal(await page.locator('.fm-comparison table').innerText(), before, 'resultado preservado ao consultar taxas')
        assert.equal(await page.locator('#fm-compare').isChecked(), true)
        const geometry = await page.locator('.fm-workspace').evaluate(element => { const left = element.children[0].getBoundingClientRect(), right = element.children[1].getBoundingClientRect(); return { left: left.x, right: right.x, width: document.documentElement.scrollWidth, viewport: innerWidth } })
        assert.ok(geometry.width <= geometry.viewport + 1, JSON.stringify(geometry))
        if (width === 1440) assert.ok(geometry.right > geometry.left + 200, 'duas colunas no desktop')
        await page.screenshot({ path: path.join(out, `${width}-${theme}-comparison.png`), fullPage: true })
        const noFgiTotal = await page.locator('.fm-comparison tbody tr').last().innerText()
        await page.locator('#fm-fgi').check()
        await page.locator('#fm-fgipct').fill('70')
        const fundedFgiTotal = await page.locator('.fm-comparison tbody tr').last().innerText()
        assert.notEqual(fundedFgiTotal, noFgiTotal, 'FGI altera os totais exibidos')
        await page.locator('#fm-fgi-inc').uncheck()
        assert.equal(await page.locator('#fm-fgi-inc').isChecked(), false)
        assert.notEqual(await page.locator('.fm-comparison tbody tr').last().innerText(), fundedFgiTotal, 'ECG à vista difere de ECG financiado')
        await page.locator('#fm-fgi-inc').check()
        assert.equal(await page.locator('.fm-comparison tbody tr').last().innerText(), fundedFgiTotal, 'restaurar ECG financiado restaura total')
        await page.screenshot({ path: path.join(out, `${width}-${theme}-fgi.png`), fullPage: true })
        await page.locator('#fm-valor').fill('')
        assert.equal(await page.locator('.fm-destaques').count(), 0, 'edição inválida remove resultado antigo')
        assert.equal(await page.locator('.fm-comparison').count(), 0)
        await page.locator('#fm-valor').fill('600.000,00')
        await page.locator('#fm-compare').uncheck()
        assert.equal(await page.locator('#fm-finame-eligible').isChecked(), true)
        await page.locator('#bw-profile').selectOption('bndes-selic-lcd')
        await page.locator('#lcd-principal').waitFor()
        assert.equal(await page.locator('#lcd-principal').inputValue(), '', 'LCD não herda condições Finame')
        await page.locator('#bw-profile').selectOption('finame-materiais')
        assert.equal(await page.locator('#fm-valor').inputValue(), '600.000,00')
        await page.getByRole('button', { name: 'Exemplo conferido · histórico', exact: true }).click()
        await page.getByText(/Não é cotação atual/).waitFor()
        assert.deepEqual(errors, [])
        report.push({ width, theme, status: 'pass' })
      } catch (error) {
        failures.push(`${width}/${theme}: ${error.message}`)
        report.push({ width, theme, status: 'fail', message: error.message })
        await page.screenshot({ path: path.join(out, `${width}-${theme}-failure.png`), fullPage: true }).catch(() => {})
      } finally { await page.close() }
    }
  } finally { fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify(report, null, 2)); await browser.close() }
  assert.deepEqual(failures, [])
})().catch(error => { console.error(error); process.exit(1) })
