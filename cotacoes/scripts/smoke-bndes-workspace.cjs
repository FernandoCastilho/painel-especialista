// A rolagem local é intencional no celular. Prova o valor inteiro da última
// alternativa, em vez de aceitar somente a captura do início da tabela.
async function proveLastColumn(region, file) {
  await region.evaluate(element => { element.scrollLeft = element.scrollWidth })
  const geometry = await region.evaluate(element => {
    const box = element.getBoundingClientRect()
    return { scrollLeft: element.scrollLeft, scrollWidth: element.scrollWidth, clientWidth: element.clientWidth, left: box.left + element.clientLeft, right: box.left + element.clientLeft + element.clientWidth, cells: [...element.querySelectorAll('tbody tr td:last-child')].map(cell => { const range = document.createRange(); range.selectNodeContents(cell); const text = range.getBoundingClientRect(); return { value: cell.textContent.trim(), left: text.left, right: text.right } }) }
  })
  assert.ok(geometry.cells.length > 0, 'última coluna contém resultados')
  if (geometry.scrollWidth > geometry.clientWidth + 1) assert.ok(geometry.scrollLeft > 0, 'região rolou até a última alternativa')
  for (const cell of geometry.cells) assert.ok(cell.left >= geometry.left - 1 && cell.right <= geometry.right + 1, `último valor completo: ${JSON.stringify({ ...geometry, cells: [cell] })}`)
  await region.screenshot({ path: file })
  await region.evaluate(element => { element.scrollLeft = 0 })
}

