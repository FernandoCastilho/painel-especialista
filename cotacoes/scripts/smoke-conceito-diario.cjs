// Conceito do dia: não abre mais sozinho. Fica no botão "Conceito do dia" da faixa Aprender, no Mercado.
const { chromium } = require('playwright'), assert = require('node:assert/strict')
const fs = require('node:fs')
;(async () => {
  const b = await chromium.launch(require('./smoke-launch.cjs')())
  const base = process.env.SMOKE_BASE_URL || 'http://127.0.0.1:8768'
  const out = process.env.CONCEITO_QA_OUTPUT || 'conceito-qa'
  fs.mkdirSync(out, { recursive: true })
  const instant = new Date('2026-11-03T02:59:00Z') // 23h59 de 02/11 em São Paulo
  const raw = (code, codein, bid) => ({ code, codein, bid: String(bid), ask: String(bid + .001), high: String(bid * 1.01), low: String(bid * .99), pctChange: '0.2', varBid: String(bid * .002), timestamp: String(instant.getTime() / 1000) })
  const quotes = { USDBRL: raw('USD', 'BRL', 5.28), EURBRL: raw('EUR', 'BRL', 5.74), JPYBRL: raw('JPY', 'BRL', .032), USDCNH: raw('USD', 'CNH', 7.23) }
  try {
    for (const width of [390, 1280]) {
      const ctx = await b.newContext({ viewport: { width, height: 800 }, timezoneId: 'Asia/Tokyo', reducedMotion: 'reduce', serviceWorkers: 'block' })
      await ctx.addInitScript(() => Object.defineProperty(navigator, 'webdriver', { get: () => false }))
      await ctx.route('**/*', r => r.request().url().startsWith(base) ? r.continue() : r.abort())
      await ctx.route('**/recado.json*', r => r.fulfill({ json: { ativo: false } }))
      // A faixa Aprender acompanha os indicadores do Mercado: cotações de teste garantem que ela apareça.
      await ctx.route('**/json/last/**', r => r.fulfill({ json: quotes }))
      await ctx.route('**/quotes.json*', r => r.fulfill({ json: { generatedAt: instant.getTime(), quotes } }))
      const p = await ctx.newPage(), errors = []
      p.setDefaultTimeout(15000)
      p.on('pageerror', e => errors.push(e.message))
      await p.clock.install({ time: instant })
      await p.goto(base + '/#resumo')
      const aviso = p.locator('dialog.aviso-inicial:not(.recado)')
      const daily = p.locator('dialog.conceito-diario')
      const button = p.locator('.insight-aprender').getByRole('button', { name: /^Conceito do dia/ })
      const idle = async (message) => { await p.clock.runFor(3000); await p.waitForTimeout(150); assert.equal(await p.locator('dialog:modal').count(), 0, message) }
      await aviso.waitFor().catch(async e => { console.error({ errors, body: (await p.locator('body').innerText()).slice(0, 500) }); throw e })
      await aviso.getByRole('button', { name: 'Entendi' }).click()
      // Depois do aviso, nada abre sozinho: o conceito espera o clique.
      await idle('conceito não abre sozinho na entrada')
      assert.equal(await daily.count(), 0)
      assert.equal(await p.evaluate(() => localStorage.getItem('aprender-conceito-dia')), null, 'nada é marcado sem abrir')
      await button.waitFor()
      assert.equal(await p.locator('.insight-aprender').getByRole('button', { name: 'Ver em Aprender ›' }).count(), 1, 'a faixa continua com o link para Aprender')
      assert.equal(await button.locator('.sinal-novo').count(), 1, 'ponto discreto enquanto o conceito de hoje não foi aberto')
      const target = await button.boundingBox()
      assert.ok(target.height >= (width < 1000 ? 44 : 32) && target.width >= 44, 'alvo do botão')
      await button.click()
      await daily.waitFor()
      assert.equal(await p.locator('dialog:modal').count(), 1)
      assert.equal(await p.evaluate(() => localStorage.getItem('aprender-conceito-dia')), '2026-11-02')
      const first = await daily.locator('h2').innerText()
      assert.equal(await daily.getByRole('button', { name: 'Fechar', exact: true }).evaluate(el => el === document.activeElement), true, await p.evaluate(() => document.activeElement.outerHTML.slice(0, 300)))
      await p.keyboard.press('Shift+Tab')
      assert.equal(await daily.evaluate(el => el.contains(document.activeElement)), true)
      await p.keyboard.press('Tab')
      assert.equal(await daily.evaluate(el => el.contains(document.activeElement)), true)
      await p.keyboard.press('Escape')
      await daily.waitFor({ state: 'detached' })
      assert.equal(await button.evaluate(el => el === document.activeElement), true, 'foco volta ao botão que abriu')
      assert.equal(await button.locator('.sinal-novo').count(), 0, 'ponto apaga depois de abrir')
      // Foco na janela e passagem do tempo não reabrem nada.
      await p.evaluate(() => window.dispatchEvent(new Event('focus')))
      await idle('foco não reabre')
      assert.equal(await aviso.count(), 0)
      // Segunda visita no mesmo dia: nem aviso, nem conceito, nem ponto.
      await p.reload(); await button.waitFor()
      await idle('retorno no mesmo dia sem pop-up')
      assert.equal(await aviso.count(), 0, 'aviso de entrada não volta com o mesmo texto')
      assert.equal(await button.locator('.sinal-novo').count(), 0)
      // Virada em São Paulo, com navegador deliberadamente em outro fuso: nada abre; ao pedir, vem o conceito do novo dia.
      await p.clock.fastForward(61000)
      await idle('virada do dia não abre o conceito')
      await button.click(); await daily.waitFor()
      assert.notEqual(await daily.locator('h2').innerText(), first)
      assert.equal(await p.evaluate(() => localStorage.getItem('aprender-conceito-dia')), '2026-11-03')
      assert.equal(await p.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      await p.screenshot({ path: `${out}/${width}.png` })
      const title = await daily.locator('h2').innerText()
      await daily.getByRole('button', { name: 'Abrir conceito completo' }).click()
      await p.waitForURL(/#aprender\//)
      await p.locator('.learn-detail h2').filter({ hasText: title }).waitFor()
      assert.equal(await p.locator('.learn-detail').evaluate(el => el === document.activeElement), true)
      assert.equal(await p.locator('dialog:modal').count(), 0)
      await p.goBack()
      assert.match(p.url(), /#resumo$/)
      await button.waitFor()
      await idle('voltar ao Mercado não reabre')
      // Recado pendente continua aparecendo, sozinho: o conceito não entra mais na fila.
      await ctx.route('**/recado.json*', r => r.fulfill({ json: { ativo: true, id: 'qa', titulo: 'Recado de teste', texto: 'Teste de fila.' } }))
      await p.evaluate(() => localStorage.removeItem('aprender-conceito-dia'))
      await p.reload()
      await p.getByRole('dialog', { name: 'Recado de teste' }).waitFor()
      assert.equal(await p.locator('dialog:modal').count(), 1)
      await p.keyboard.press('Escape')
      await idle('depois do recado, nada mais abre')
      // Armazenamento bloqueado: o botão continua abrindo o conceito.
      await p.evaluate(() => Object.defineProperty(window, 'localStorage', { configurable: true, get() { throw new Error('bloqueado') } }))
      await button.click(); await daily.waitFor()
      await daily.getByRole('button', { name: 'Fechar', exact: true }).click()
      await daily.waitFor({ state: 'detached' })
      await idle('fechado continua fechado')
      assert.deepEqual(errors, [])
      await ctx.close()
      console.log(`${width} PASS sem abertura automática, botão da faixa, data SP, navegação, foco, Escape, recado e reduced motion`)
    }
  } finally { await b.close() }
})().catch(e => { console.error(e); process.exit(1) })
