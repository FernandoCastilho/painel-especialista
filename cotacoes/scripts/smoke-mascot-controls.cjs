const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const base = process.env.SMOKE_BASE_URL || 'http://127.0.0.1:5231'
const output = process.env.MASCOT_QA_OUTPUT || '/tmp/owl-qa'
fs.mkdirSync(output, { recursive: true })
;(async () => {
  const browser = await chromium.launch(require('./smoke-launch.cjs')())
  try {
    for (const width of [360, 390, 1280]) {
      const context = await browser.newContext({ viewport: { width, height: 900 }, serviceWorkers: 'block' })
      const page = await context.newPage(), errors = [], posts = []
      page.on('pageerror', error => errors.push(error.message))
      await page.route('**/*', route => {
        const request = route.request(), url = new URL(request.url())
        if (request.method() === 'POST') { posts.push(url.href); return route.fulfill({ json: { ok: true } }) }
        if (url.origin !== new URL(base).origin) return route.fulfill({ status: 503, body: 'offline' })
        if (url.pathname.endsWith('/calendar.json')) return route.fulfill({ status: 503, body: 'offline' })
        return route.continue()
      })
      await page.goto(base + '/#calculadora/giro')
      const move = page.getByRole('button', { name: 'Mover mascote', exact: true })
      await move.scrollIntoViewIfNeeded()
      const dock = page.locator('.mascot-dock')
      assert.equal(await page.locator('.feedback-trigger img').evaluateAll(els => els.length === 2 && els.every(el => el.complete && el.naturalWidth > 0)), true)
      assert.equal(await dock.evaluate(el => getComputedStyle(el).position), 'fixed')
      assert.equal(await dock.evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)')
      const before = await dock.boundingBox()
      await move.focus(); await page.keyboard.press('ArrowLeft')
      const after = await dock.boundingBox()
      assert.ok(after.x <= before.x)
      await move.click(); await page.getByRole('button', { name: 'Mover para direita' }).click()
      await page.getByRole('button', { name: 'Posição inicial' }).click()
      await page.getByRole('button', { name: 'Concluir', exact: true }).click()
      const handle = await move.boundingBox()
      await page.mouse.move(handle.x + 20, handle.y + 20); await page.mouse.down(); await page.mouse.move(10, 10, { steps: 8 }); await page.mouse.up()
      const bounds = await dock.boundingBox()
      assert.ok(bounds.x >= 0)
      if (width >= 1000) {
        const header = await page.locator('.term-head').boundingBox()
        assert.ok(bounds.y >= header.y + header.height, 'desktop controls must stay below header')
      }
      await page.getByRole('button', { name: 'Ocultar mascote' }).click()
      const restore = page.getByRole('button', { name: 'Mostrar mascote' })
      await restore.waitFor(); assert.equal(await restore.evaluate(el => el === document.activeElement), true)
      await page.reload(); await restore.click(); await move.waitFor()
      const search = page.getByRole('button', { name: 'Pesquisar', exact: false })
      await search.click()
      const dialog = page.getByRole('dialog', { name: 'Buscar no painel' })
      await dialog.waitFor(); assert.ok(await dialog.evaluate(el => el.classList.contains('global-search-bubble')))
      const input = dialog.getByRole('searchbox')
      assert.equal(await input.evaluate(el => el === document.activeElement), true)
      await input.fill('inadimplência')
      await dialog.locator('.global-search-results[aria-busy="false"]').waitFor()
      await dialog.locator('.search-coverage').waitFor()
      assert.ok(await dialog.locator('.global-search-result').count() > 0)
      await page.screenshot({ path: `${output}/search-${width}.png` })
      await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'hidden' })
      assert.equal(await search.evaluate(el => el === document.activeElement), true)
      await page.keyboard.press('Control+Shift+F'); await dialog.waitFor()
      assert.equal(await dialog.evaluate(el => el.classList.contains('global-search-bubble')), false)
      await input.fill('FIDC'); await dialog.locator('.global-search-results[aria-busy="false"]').waitFor()
      await dialog.getByRole('button', { name: /^FIDC/ }).first().click()
      await page.locator('.search-destination').waitFor(); assert.match(page.url(), /#aprender\/fidc$/)
      await page.getByRole('button', { name: 'Abrir caixa de sugestões' }).click()
      await page.getByLabel('Mensagem (obrigatória)').fill('Teste local com transporte interceptado')
      await page.getByRole('button', { name: 'Enviar mensagem', exact: true }).click()
      await page.getByText('Mensagem recebida pelo serviço. Obrigado pela contribuição!').waitFor()
      assert.deepEqual(posts, ['https://formspree.io/f/xaeegypp'])
      await page.getByRole('button', { name: 'Fechar caixa de sugestões' }).click()
      await page.setViewportSize({ width: 320, height: 568 }); await move.scrollIntoViewIfNeeded()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('painel.mascot.ui.v1')))
      assert.deepEqual(Object.keys(saved).sort(), ['desktop', 'hidden'])
      assert.deepEqual(errors, [])
      await context.close(); console.log(`PASS owl controls, real search and mocked feedback ${width}`)
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
