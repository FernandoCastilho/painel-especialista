const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
;(async()=>{
 const browser=await chromium.launch(require('./smoke-launch.cjs')())
 const base=process.env.SMOKE_PUBLISHED_URL||process.env.SMOKE_BASE_URL||'http://127.0.0.1:5237'
 const out=process.env.PUBLISHED_QA_OUTPUT||process.env.SMOKE_OUT||'/tmp/iof-qa';fs.mkdirSync(out,{recursive:true})
 try {for(const width of [390,1280]) {
  const page=await browser.newPage({viewport:{width,height:1000}}),errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto(base+'/#calculadora/analise-desconto')
  await page.locator('#ad-titleFeeMode').waitFor()
  const notice=page.getByRole('dialog',{name:'Aviso',exact:true});if(await notice.isVisible())await notice.getByRole('button',{name:'Entendi',exact:true}).click()
  // Abre sem vermelho; o erro de um campo só aparece depois de a pessoa passar por ele e sair.
  assert.equal(await page.locator('.cx-desconto [aria-invalid=true], .cx-desconto [role=alert]').count(),0)
  assert.match(await page.locator('.desconto-result-status').innerText(),/Escolha como a tarifa dos títulos é cobrada para ver a comparação/)
  await page.locator('#ad-titleFeeMode').focus();await page.locator('#ad-titleFeeMode').blur()
  assert.equal(await page.locator('#ad-titleFeeMode').getAttribute('aria-invalid'),'true')
  assert.match(await page.locator('.desconto-result-status').innerText(),/Preencha ou corrija/)
  await page.locator('#ad-titleFeeMode').selectOption('percent')
  // Entrada por prazo médio (24/11/2026): a tela abre nela, com o borderô hipotético; mudar o prazo muda o resultado.
  assert.equal(await page.locator('#ad-titleMode').inputValue(),'average')
  assert.match(await page.locator('.dsc-bordero').innerText(),/Estimativa: 30 boletos.*vencendo em 15 a 45 dias/s)
  const medio=await page.locator('.rt-result').innerText()
  await page.locator('#ad-averageDays').fill('60')
  assert.notEqual(await page.locator('.rt-result').innerText(),medio)
  assert.match(await page.locator('.dsc-bordero').innerText(),/vencendo em 30 a 90 dias/)
  await page.locator('.dsc-bordero summary').click()
  assert.equal(await page.locator('.dsc-bordero tbody tr').count()>1,true)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false)
  await page.screenshot({path:`${out}/desconto-prazo-medio-${width}.png`,fullPage:true})
  // Daqui em diante, o borderô título a título.
  await page.locator('#ad-titleMode').selectOption('titles')
  assert.equal(await page.locator('#ad-iofPaid, #ad-interest, #ad-iofAdditional').count(),0)
  // Roteiro de 21/11/2026: os números do desconto ficam no bloco "3 Resultado" (a linha do tempo saiu no mesmo dia).
  const before=await page.locator('.rt-result').innerText()
  await page.locator('#ad-operationRate').fill('3,66')
  assert.notEqual(await page.locator('.rt-result').innerText(),before)
  // Padrão de 18/11/2026: as tabelas completas ficam recolhidas; abre para conferir os totais.
  await page.locator('details.dsc-tables > summary').click()
  const totals=await page.locator('.desconto-summary-panel').innerText()
  await page.locator('#ad-averageValue').fill('451200,86')
  assert.notEqual(await page.locator('.desconto-summary-panel').innerText(),totals)
  await page.getByRole('button',{name:'Adicionar grupo de títulos',exact:true}).click()
  await page.getByRole('button',{name:'Remover grupo 2',exact:true}).click()
  await page.locator('#ad-operations').fill('')
  await page.locator('#ad-operations').blur()
  assert.match(await page.locator('.desconto-result-status').innerText(),/Preencha ou corrija/)
  assert.equal(await page.locator('#ad-operations').getAttribute('aria-invalid'),'true')
  await page.locator('#ad-operations').fill('6')
  assert.doesNotMatch(await page.locator('.desconto-summary-panel').innerText(),/NaN|Infinity/)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false)
  await page.screenshot({path:`${out}/desconto-${width}.png`,fullPage:true})
  assert.deepEqual(errors,[]);await page.close()
 }console.log('Desconto IOF: interação e responsividade 390/1280 OK')}finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
