const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const base = process.env.SMOKE_BASE_URL || 'http://127.0.0.1:8768'
const out = process.env.CBS_QA_OUTPUT || 'workspace-qa/cbs'
async function run() {
  fs.mkdirSync(out, { recursive: true })
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, headless: true, args: ['--no-sandbox'] })
  const errors = []
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, hasTouch: true })
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/*', route => route.request().url().startsWith(base + '/') ? route.continue() : route.abort())
    await page.goto(base + '/#calculadora/cbs-caixa')
    await page.getByRole('heading', { name: 'Faturamento e necessidade de giro' }).waitFor()
    assert.equal(await page.locator('#cbs-revenue').inputValue(), '3.000.000,00')
    assert.equal(await page.locator('#cbs-regime').inputValue(), 'presumido')
    assert.equal(await page.locator('#cbs-year').inputValue(), '2027')
    assert.match(await page.locator('.cbs-rates').innerText(), /Alíquotas de 2027\s*hipótese/)
    assert.match(await page.locator('.cbs-rates').innerText(), /TCU/)
    assert.equal(await page.locator('#cbs-cbsRate').inputValue(), '11,2')
    await page.locator('#cbs-year').selectOption('2026')
    assert.match(await page.locator('.cbs-rates').innerText(), /Alíquotas de 2026\s*oficial[\s\S]*CBS 0,9% · IBS estadual 0,1% · IBS municipal 0%/)
    assert.equal(await page.locator('#cbs-cbsRate').count(), 0, 'official 2026 rates are not editable')
    await page.locator('#cbs-year').selectOption('2033')
    assert.equal(await page.locator('#cbs-ibsUfRate').inputValue(), '16')
    await page.locator('#cbs-year').selectOption('2027')
    assert.match(await page.locator('.cbs-rates').innerText(), /tabela V\d{4} de \d{2}\/\d{2}\/\d{4}/)
    assert.match(await page.locator('.cbs-official-source').textContent(), /Licença MIT/)
    // Exemplo inicial completo: calcula sem alerta e com NCG.
    assert.equal(await page.locator('.cbs-result').count(), 1, 'initial example must calculate')
    assert.equal(await page.locator('.cbs-alerts').count(), 0, 'initial example must not show alerts')
    assert.doesNotMatch(await page.locator('body').innerText(), /NCG não calculada/)
    assert.match(await page.locator('.cbs-headline').innerText(), /imposto por mês\s*hipótese/i)
    await page.locator('#cbs-year').selectOption('2026')
    await page.locator('.cbs-illustrative').waitFor()
    assert.equal(await page.locator('.calc-result-shell').count(), 0, '2026 has no reserve')
    assert.equal(await page.locator('#cbs-currentNetRate').count(), 0, '2026 replaces no tax')
    assert.ok((await page.locator('.cbs-illustrative').innerText()).replace(/\s/g, '').includes('R$27.000,00'), '2026: 0,9% de R$ 3 milhões')
    for (const theme of ['light', 'dark']) for (const width of [390, 1440]) {
      await page.emulateMedia({ colorScheme: theme })
      await page.setViewportSize({ width, height: width === 390 ? 844 : 1100 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `2026 overflow ${theme}/${width}`)
      await page.screenshot({ path: path.join(out, `ano-2026-${theme}-${width}.png`), fullPage: true })
    }
    await page.locator('#cbs-year').selectOption('2027')
    for (const theme of ['light', 'dark']) for (const width of [390, 1440]) {
      await page.emulateMedia({ colorScheme: theme })
      await page.setViewportSize({ width, height: width === 390 ? 844 : 1100 })
      await page.screenshot({ path: path.join(out, `cenario-inicial-${theme}-${width}.png`), fullPage: true })
    }
    await page.locator('#cbs-cmv').fill('')
    assert.match(await page.locator('body').innerText(), /NCG não calculada/)
    await page.locator('#cbs-cmv').fill('2.000.000,00')
    await page.locator('#cbs-purchases').fill('2.000.000,00')
    assert.match(await page.locator('body').innerText(), /7\.000\.000,00/)
    await page.getByText('Editar meses e ver valores', { exact: true }).click()
    assert.match(await page.locator('#overview-month-0').locator('xpath=ancestor::div[contains(@class,"cx-field")]').innerText(), /7\.000\.000,00/)
    assert.match(await page.locator('.cbs-overview').innerText(), /NCG operacional simplificada[^:]*: R\$\s?7\.000\.000,00, igual em todos os meses/)
    assert.equal(await page.locator('.cbs-overview details').evaluate(el => el.open), true, 'opened by the test, closed by default')
    for (const theme of ['light', 'dark']) for (const width of [390, 1440]) {
      await page.emulateMedia({ colorScheme: theme })
      await page.setViewportSize({ width, height: width === 390 ? 844 : 1100 })
      await page.screenshot({ path: path.join(out, `ncg-sintetica-${theme}-${width}.png`), fullPage: true })
    }
    await page.locator('#cbs-cmv').fill('')
    assert.match(await page.locator('body').innerText(), /NCG não calculada/)
    assert.equal(await page.getByRole('img', { name: /NCG operacional simplificada/ }).count(), 0)
    await page.locator('#cbs-group').fill('46.3')
    await page.locator('#cbs-group').press('ArrowDown')
    await page.locator('#cbs-group').press('Enter')
    await page.locator('#cbs-currentNetRate').fill('3,65')
    await page.locator('#cbs-revenue').fill('1.000.000,00')
    await page.locator('#cbs-receiveDays').fill('30')
    await page.locator('#cbs-payDays').fill('30')
    await page.locator('#cbs-stockDays').fill('30')
    await page.getByRole('heading', { name: 'Reserva adicional para cobrir os prazos' }).waitFor()
    await page.locator('.cbs-calculation > summary').click()
    // Padrão de 18/11/2026: o mês a mês fica recolhido dentro do resultado; abre para conferir os 12 meses.
    await page.locator('.cbs-annual-details > summary').click()
    const { simulateCbsCash } = await import('../src/cbsCash.js')
    const snapshot = JSON.parse(fs.readFileSync(path.join(__dirname, '../src/ibgeCbsSnapshot.json'), 'utf8'))
    const taxes = { regime: 'regular', aliquotas: { cbs: 11.2, ibsUf: 0.05, ibsMun: 0.05 }, reducao: {}, isRate: 0 }
    const expected = change => simulateCbsCash({ revenue: 1000000, spendingRatio: snapshot.datasets.find(d => d.kind === 'comercio').groups.find(g => g.id === 'comercio-83319').spendingRatio, eligibleShare: 70, taxes, currentNetRate: 3.65, splitShare: 50, receiveDays: 30, payDays: 30, stockDays: 30, currentDueDays: 40, futureDueDays: 40, creditDelayDays: 30, ...change })
    const format = value => value.toLocaleString('pt-BR', { style: 'currency', currency: 'BRL' }).replace(/\s/g, '')
    async function checkReserves(result) {
      const values = await page.locator('.cbs-scenarios strong').allTextContents()
      assert.deepEqual(values.map(value => value.replace(/\s/g, '')), [format(result.reserveImmediate), format(result.reserveDelayed)])
    }
    await checkReserves(expected({}))
    assert.equal((await page.locator('.cbs-primary-value').first().innerText()).replace(/\s/g, ''), format(expected({}).reserveDelayed))
    const monthly = async () => (await page.locator('.cbs-monthly-tax').innerText()).replace(/\s/g, '')
    assert.ok((await monthly()).includes(format(expected({}).cbs)), 'CBS por fora no resultado')
    assert.ok((await monthly()).includes(format(expected({}).ibs)), 'IBS no resultado')
    // Redução oficial de 60% (educação, cClassTrib 200028): alíquota × (1 − 0,6).
    await page.locator('#cbs-reduction').selectOption('200028')
    const reduced = expected({ taxes: { ...taxes, reducao: { cbs: 60, ibsUf: 60, ibsMun: 60 } } })
    await checkReserves(reduced)
    assert.ok((await monthly()).includes(format(reduced.cbs)))
    await page.locator('#cbs-reduction').selectOption('')
    await checkReserves(expected({}))
    await page.locator('.cbs-month-editor > summary').click()
    await page.locator('#cbs-month-1').fill('2.000.000,00')
    await page.getByRole('button', { name: 'Fev', exact: true }).click()
    assert.ok((await page.locator('.cbs-month-reading').innerText()).replace(/\s/g, '').includes(format(expected({ revenue: 2000000 }).reserveDelayed)))
    await page.locator('#cbs-month-1').fill('0')
    assert.equal(await page.locator('.cbs-annual-chart .cbs-chart-dot').count(), 11, 'invalid month must create a gap')
    assert.match(await page.locator('.cbs-month-reading').innerText(), /inválido/)
    await page.getByRole('button', { name: 'Usar faturamento principal em todos', exact: true }).click()
    await page.locator('.cbs-month-editor > summary').click()
    for (const theme of ['light', 'dark']) {
      await page.emulateMedia({ colorScheme: theme })
      for (const width of [390, 1440]) {
        await page.setViewportSize({ width, height: width === 390 ? 844 : 1100 })
        await page.evaluate(() => document.fonts.ready)
        const overflow = await page.evaluate(() => ({ overflow: document.documentElement.scrollWidth > innerWidth, offenders: [...document.querySelectorAll('body *')].filter(el => el.getBoundingClientRect().right > innerWidth + 1).slice(0, 12).map(el => ({tag:el.tagName, className:String(el.className), right:el.getBoundingClientRect().right})) }))
        assert.equal(overflow.overflow, false, `overflow ${theme}/${width}: ${JSON.stringify(overflow.offenders)}`)
        assert.equal(await page.locator('.cbs-annual-chart').evaluate(element => {
          const points = [...element.querySelectorAll('circle')]
          const labels = [...element.querySelectorAll('text')]
          return points.length === 12 && points.every((point, index) => {
            const p = point.getBoundingClientRect(), label = labels[index].getBoundingClientRect()
            return Math.abs(p.x + p.width / 2 - label.x - label.width / 2) < 1
          })
        }), true, `month labels must align with points ${theme}/${width}`)
        await page.screenshot({ path: path.join(out, `${theme}-${width}.png`), fullPage: true })
        await page.locator('#cbs-group').fill('alimen')
        assert.equal(await page.getByRole('option').count() > 0, true)
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `search overflow ${theme}/${width}`)
        await page.screenshot({ path: path.join(out, `search-${theme}-${width}.png`), fullPage: true })
        if (width === 390) {
          await page.locator('#cbs-group').evaluate(element => element.scrollIntoView({ block: 'center' }))
          assert.equal(await page.locator('#cbs-group').evaluate(element => {
            const rect = element.getBoundingClientRect()
            return document.elementFromPoint(rect.left + rect.width / 2, rect.top + rect.height / 2) === element
          }), true, 'mobile search covered by navigation')
          await page.screenshot({ path: path.join(out, `search-viewport-${theme}-390.png`) })
        }
        await page.locator('#cbs-group').press('Escape')
        await page.locator('#cbs-group').fill('')
        await page.locator('#cbs-group').press('Escape')
      }
    }
    await page.getByText('Ajustar hipóteses', { exact: true }).click()
    await page.getByText('Como isso aparece no recebimento e nos prazos?', { exact: true }).click()
    await page.getByText('Uma reserva de prazo significa pagar esse valor a mais todo mês?', { exact: true }).click()
    assert.match(await page.locator('.cbs-check').innerText(), /diferença mensal do imposto/)
    assert.equal(await page.locator('.cbs-scenarios strong').count(), 2)
    await page.locator('#cbs-receiveDays').fill('60')
    await page.locator('#cbs-payDays').fill('90')
    await page.locator('#cbs-stockDays').fill('0')
    await page.locator('#cbs-creditDelayDays').fill('60')
    await page.locator('#cbs-splitShare').fill('100')
    await checkReserves(expected({ receiveDays: 60, payDays: 90, stockDays: 0, creditDelayDays: 60, splitShare: 100 }))
    assert.match(await page.locator('.cbs-result-note').innerText(), /dias no modelo/)
    const selectedBefore = await page.locator('#cbs-activity-selected').innerText()
    const reserveBefore = await page.locator('.cbs-scenarios').innerText()
    await page.locator('#cbs-group').fill('atividadequenaoexiste999')
    assert.match(await page.locator('.cbs-activity-results').innerText(), /Nenhuma atividade encontrada/)
    assert.equal(await page.locator('#cbs-activity-selected').innerText(), selectedBefore)
    assert.equal(await page.locator('.cbs-scenarios').innerText(), reserveBefore)
    await page.locator('#cbs-group').press('Escape')
    assert.equal(await page.locator('#cbs-group').getAttribute('aria-expanded'), 'false')
    await page.locator('#cbs-group').fill('alimen')
    await page.locator('#cbs-revenue').focus()
    assert.equal(await page.locator('#cbs-group').getAttribute('aria-expanded'), 'false')
    assert.equal(await page.locator('#cbs-activity-selected').innerText(), selectedBefore)
    await page.locator('#cbs-spendingPct').fill('30')
    await page.locator('#cbs-group').fill('FABRICACAO ALIMENT')
    await page.locator('#cbs-group').press('ArrowDown')
    await page.locator('#cbs-group').press('Enter')
    assert.match(await page.locator('#cbs-activity-selected').innerText(), /Indústria/)
    const industryFood = snapshot.datasets.find(d => d.kind === 'industria').groups.find(g => g.id === 'industria-116911')
    assert.equal(await page.locator('#cbs-spendingPct').inputValue(), (industryFood.spendingRatio * 100).toLocaleString('pt-BR', { maximumFractionDigits: 2 }))
    await page.setViewportSize({ width: 390, height: 844 })
    await page.locator('#cbs-group').fill('transporte servicos')
    await page.getByRole('option').first().tap()
    assert.match(await page.locator('#cbs-activity-selected').innerText(), /Serviços/)
    await page.locator('#cbs-regime').selectOption('simples')
    assert.equal(await page.locator('.cbs-result').count(), 0, 'Simples needs the DAS shares before calculating')
    assert.match(await page.locator('.cbs-alerts').innerText(), /parte de CBS e a parte de IBS/)
    await page.locator('#cbs-simplesCbs').fill('2,75')
    await page.locator('#cbs-simplesIbs').fill('1,25')
    await page.locator('.cbs-result').waitFor()
    const monthlySimples = (await page.locator('.cbs-monthly-tax').innerText()).replace(/\s/g, '')
    assert.ok(monthlySimples.includes('R$27.500,00') && monthlySimples.includes('R$12.500,00'), 'Simples: 2,75% e 1,25% de R$ 1 milhão')
    assert.doesNotMatch(await page.locator('.cbs-cash-details').textContent(), /Mais CBS/, 'Simples: DAS já está na receita bruta')
    assert.match(await page.locator('.cbs-cash-details').textContent(), /Receita bruta \(já inclui o DAS\)/)
    for (const theme of ['light', 'dark']) for (const width of [390, 1440]) {
      await page.emulateMedia({ colorScheme: theme })
      await page.setViewportSize({ width, height: width === 390 ? 844 : 1100 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `simples overflow ${theme}/${width}`)
      await page.screenshot({ path: path.join(out, `simples-${theme}-${width}.png`), fullPage: true })
    }
    await page.locator('#cbs-simples-tipo').selectOption('4')
    assert.match(await page.locator('.cbs-notes').innerText(), /suspensos/)
    await page.locator('#cbs-year').selectOption('2026')
    assert.equal(await page.locator('.cbs-result').count(), 0, 'Simples has no CBS/IBS in the DAS in 2026')
    assert.match(await page.locator('.cbs-alerts').innerText(), /Em 2026 o Simples/)
    await page.getByRole('button', { name: 'Restaurar exemplo' }).click()
    assert.equal(await page.locator('#cbs-group').inputValue(), '')
    assert.match(await page.locator('#cbs-activity-selected').innerText(), /46\.3/)
    await page.locator('#cbs-receiveDays').fill('')
    assert.equal(await page.locator('.cbs-result').count(), 0, 'invalid days still calculate')
    await page.locator('#cbs-receiveDays').fill('30')
    const help = page.getByRole('button', { name: 'Ajuda: Recebimento médio', exact: true })
    await help.click()
    await page.getByRole('dialog').waitFor()
    await page.keyboard.press('Escape')
    assert.equal(await help.evaluate(element => document.activeElement === element), true)
    await page.goto(base + '/#aprender/reforma-tributaria')
    await page.locator('.learn-app .learn-go').click()
    await page.getByRole('heading', { name: 'Faturamento e necessidade de giro' }).waitFor()
    assert.ok(page.url().endsWith('#calculadora/cbs-caixa'))
    assert.deepEqual(errors, [])
    const result = { passed: true, views: ['light-390', 'light-1440', 'dark-390', 'dark-1440'], activitySearch: { noMatchPreservesCalculation: true, keyboardSelection: true, touchSelection: true, blurAndEscape: true, crossSector: true, resetsSpendingReference: true, restoreExample: true }, sectorSwitch: true, simplesGuard: true, simplesDas: true, yearSelector: true, officialReduction: true, invalidInputGuard: true, helpEscapeFocus: true, pageErrors: errors }
    fs.writeFileSync(path.join(out, 'result.json'), JSON.stringify(result, null, 2))
    console.log(JSON.stringify(result))
  } finally { await browser.close() }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
