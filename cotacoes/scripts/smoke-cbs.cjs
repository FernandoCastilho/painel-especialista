const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const base = process.env.SMOKE_BASE_URL || 'http://127.0.0.1:8768'
const out = process.env.CBS_QA_OUTPUT || 'workspace-qa/cbs'
async function run() {
  fs.mkdirSync(out, { recursive: true })
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, headless: true, args: ['--no-sandbox'] })
  const errors = []
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, hasTouch: true })
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/*', route => route.request().url().startsWith(base + '/') ? route.continue() : route.abort())
    await page.goto(base + '/#calculadora/cbs-caixa')
    await page.getByRole('heading', { name: '3. Necessidade adicional de giro' }).waitFor()
    const { simulateCbsCash } = await import('../src/cbsCash.js')
    const snapshot = JSON.parse(fs.readFileSync(path.join(__dirname, '../src/ibgeCbsSnapshot.json'), 'utf8'))
    const expected = change => simulateCbsCash({ revenue: 1000000, spendingRatio: snapshot.datasets.find(d => d.kind === 'comercio').groups.find(g => g.id === 'comercio-83319').spendingRatio, eligibleShare: 70, cbsRate: 11.2, currentNetRate: 3.65, splitShare: 50, receiveDays: 30, payDays: 30, stockDays: 30, currentDueDays: 40, futureDueDays: 40, creditDelayDays: 30, ...change })
    const format = value => value.toLocaleString('pt-BR', { style: 'currency', currency: 'BRL' }).replace(/\s/g, '')
    async function checkReserves(result) {
      const values = await page.locator('.cbs-scenarios strong').allTextContents()
      assert.deepEqual(values.map(value => value.replace(/\s/g, '')), [format(result.reserveImmediate), format(result.reserveDelayed)])
    }
    await checkReserves(expected({}))
    for (const theme of ['light', 'dark']) {
      await page.emulateMedia({ colorScheme: theme })
      for (const width of [390, 1440]) {
        await page.setViewportSize({ width, height: width === 390 ? 844 : 1100 })
        await page.evaluate(() => document.fonts.ready)
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `overflow ${theme}/${width}`)
        await page.screenshot({ path: path.join(out, `${theme}-${width}.png`), fullPage: true })
        await page.locator('#cbs-group').fill('alimen')
        assert.equal(await page.getByRole('option').count() > 0, true)
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `search overflow ${theme}/${width}`)
        await page.screenshot({ path: path.join(out, `search-${theme}-${width}.png`), fullPage: true })
        if (width === 390) {
          await page.locator('#cbs-group').evaluate(element => element.scrollIntoView({ block: 'center' }))
          assert.equal(await page.locator('#cbs-group').evaluate(element => {
            const rect = element.getBoundingClientRect()
            return document.elementFromPoint(rect.left + rect.width / 2, rect.top + rect.height / 2) === element
          }), true, 'mobile search covered by navigation')
          await page.screenshot({ path: path.join(out, `search-viewport-${theme}-390.png`) })
        }
        await page.locator('#cbs-group').press('Escape')
        await page.locator('#cbs-group').fill('')
        await page.locator('#cbs-group').press('Escape')
      }
    }
    await page.getByText('Ajustar impostos, créditos e prazos', { exact: true }).click()
    await page.getByText('Como isso aparece no recebimento e nos prazos?', { exact: true }).click()
    await page.getByText('Uma reserva de prazo significa pagar esse valor a mais todo mês?', { exact: true }).click()
    assert.match(await page.locator('.cbs-check').innerText(), /diferença mensal do imposto/)
    assert.equal(await page.locator('.cbs-scenarios strong').count(), 2)
    await page.locator('#cbs-receiveDays').fill('60')
    await page.locator('#cbs-payDays').fill('90')
    await page.locator('#cbs-stockDays').fill('0')
    await page.locator('#cbs-creditDelayDays').fill('60')
    await page.locator('#cbs-splitShare').fill('100')
    await checkReserves(expected({ receiveDays: 60, payDays: 90, stockDays: 0, creditDelayDays: 60, splitShare: 100 }))
    assert.match(await page.locator('.cbs-result-note').innerText(), /dias no modelo/)
    const selectedBefore = await page.locator('#cbs-activity-selected').innerText()
    const reserveBefore = await page.locator('.cbs-scenarios').innerText()
    await page.locator('#cbs-group').fill('atividadequenaoexiste999')
    assert.match(await page.locator('.cbs-activity-results').innerText(), /Nenhuma atividade encontrada/)
    assert.equal(await page.locator('#cbs-activity-selected').innerText(), selectedBefore)
    assert.equal(await page.locator('.cbs-scenarios').innerText(), reserveBefore)
    await page.locator('#cbs-group').press('Escape')
    assert.equal(await page.locator('#cbs-group').getAttribute('aria-expanded'), 'false')
    await page.locator('#cbs-group').fill('alimen')
    await page.locator('#cbs-revenue').focus()
    assert.equal(await page.locator('#cbs-group').getAttribute('aria-expanded'), 'false')
    assert.equal(await page.locator('#cbs-activity-selected').innerText(), selectedBefore)
    await page.locator('#cbs-spendingPct').fill('30')
    await page.locator('#cbs-group').fill('FABRICACAO ALIMENT')
    await page.locator('#cbs-group').press('ArrowDown')
    await page.locator('#cbs-group').press('Enter')
    assert.match(await page.locator('#cbs-activity-selected').innerText(), /Indústria/)
    const industryFood = snapshot.datasets.find(d => d.kind === 'industria').groups.find(g => g.id === 'industria-116911')
    assert.equal(await page.locator('#cbs-spendingPct').inputValue(), (industryFood.spendingRatio * 100).toLocaleString('pt-BR', { maximumFractionDigits: 2 }))
    await page.setViewportSize({ width: 390, height: 844 })
    await page.locator('#cbs-group').fill('transporte servicos')
    await page.getByRole('option').first().tap()
    assert.match(await page.locator('#cbs-activity-selected').innerText(), /Serviços/)
    await page.locator('#cbs-regime').selectOption('simples')
    assert.equal(await page.locator('.cbs-result').count(), 0, 'Simples must not calculate regular model')
    await page.getByRole('button', { name: 'Restaurar exemplo' }).click()
    assert.equal(await page.locator('#cbs-group').inputValue(), '')
    assert.match(await page.locator('#cbs-activity-selected').innerText(), /46\.3/)
    await page.locator('#cbs-receiveDays').fill('')
    assert.equal(await page.locator('.cbs-result').count(), 0, 'invalid days still calculate')
    await page.locator('#cbs-receiveDays').fill('30')
    const help = page.getByRole('button', { name: 'Ajuda: Recebimento médio', exact: true })
    await help.click()
    await page.getByRole('dialog').waitFor()
    await page.keyboard.press('Escape')
    assert.equal(await help.evaluate(element => document.activeElement === element), true)
    await page.goto(base + '/#aprender/reforma-tributaria')
    await page.locator('.learn-app .learn-go').click()
    await page.getByRole('heading', { name: '3. Necessidade adicional de giro' }).waitFor()
    assert.ok(page.url().endsWith('#calculadora/cbs-caixa'))
    assert.deepEqual(errors, [])
    const result = { passed: true, views: ['light-390', 'light-1440', 'dark-390', 'dark-1440'], activitySearch: { noMatchPreservesCalculation: true, keyboardSelection: true, touchSelection: true, blurAndEscape: true, crossSector: true, resetsSpendingReference: true, restoreExample: true }, sectorSwitch: true, simplesGuard: true, invalidInputGuard: true, helpEscapeFocus: true, pageErrors: errors }
    fs.writeFileSync(path.join(out, 'result.json'), JSON.stringify(result, null, 2))
    console.log(JSON.stringify(result))
  } finally { await browser.close() }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
